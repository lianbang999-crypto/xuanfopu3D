// 取本位三段。text＝位文（已去「譜曰。」）。返回 { jie, act, post }，无者为空串。
export function sfpSplitOf(name, text) {
  const v = SFP_CANON_SPLIT[name];
  const t = String(text || '');
  if (!v) return { jie: t, act: '', post: '' };
  const act = typeof v === 'string' ? v : v.act;
  const post = typeof v === 'string' ? null : v.post;
  const a = act ? t.indexOf(act) : -1;
  if (a < 0) return { jie: t, act: '', post: '' };
  const p = post ? t.indexOf(post) : -1;
  return p > a
    ? { jie: t.slice(0, a), act: t.slice(a, p), post: t.slice(p) }
    : { jie: t.slice(0, a), act: t.slice(a), post: '' };
}

