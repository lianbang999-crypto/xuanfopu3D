// 用法：ico('hall') 直接拼进 innerHTML。aria-hidden 是因为图标旁边一律另有文字或 aria-label，
// 读屏念一遍按钮名就够了，不该再念一次图形。
export function ico(name, cls = '') {
  const d = SHAPES[name];
  if (!d) return '';
  return `<svg class="ico${cls ? ` ${cls}` : ''}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${d}</svg>`;
}

