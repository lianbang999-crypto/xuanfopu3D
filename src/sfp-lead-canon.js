// 缘起：复刻自线上 V104 的手工逐组层、话头改写层、通例层，其话头用词有三处不合卷首定诠——
//   ① 用「布施／持戒／禅定／智慧」，而卷首〈輪相表法第一〉原词是「施善／戒善／定善／善慧」；
//   ② 用「夹一分」，而全谱「一分」仅三见（下劣脩羅一分／智少一分／各增一分三德），无一与轮相相干；
//      谱主的表法是一轮一字，说「一轮X、一轮Y」即足。
//   ③ 通例句作「正好相抵……善压不住恶、恶也盖不过善」，把谱曰「相為對治」读成了等量对消。
//      谱主紧接一问自破此解：「問：那佛、謨佛亦可善惡相治，何以仍行？答：有漏惡劣，不能障無漏善令
//      總不行，但令無漏力弱，不獲深妙益耳。」——胜负全看善之品位，有漏之施戒定遇二惑才「二俱無力」。
//   又：诸门另有明文改判六字取义者，全谱只二处（见下 POS_GLYPH），通表硬套会说错。
//
// 立法：上游数据文件（sfp-door*-why.js／sfp-combo-why.js／sfp-stay-why.js／sfp-norm.js）一律不动，
//   保持与线上逐字一致，便于日后再复刻；校正全部集中在本层，且**只改话头，判语一字不动**。
//   scripts/check-lead-canon.mjs 逐格把守：话头须在 KNOWN_LEADS 内、改后须等于 canonLeadOf、
//   话头之后的判语须与上游逐字相同。

// ── 卷首〈輪相表法第一〉逐字定诠 ──
// 「那表屬見煩惱……謨表屬愛煩惱……阿表施善，彌表戒善，陀表定善，佛表善慧。
//   或阿彌陀表有漏善，佛表無漏善。」
// 佛取「无漏善慧」＝合第一重（善慧）与第二重（无漏善）而言，上游手写层亦用此词。
export const CANON_GLYPH = { 那: '见烦恼', 謨: '爱烦恼', 阿: '施善', 彌: '戒善', 陀: '定善', 佛: '无漏善慧' };

// ── 诸门明文改判者（全谱只此二处，逐字见下）──
// 卷五〈鈍根阿那含〉譜曰：「問：那謨二字既表見愛，若有見愛，何成四果？答：界內見惑初果先已斷盡，
//   界內愛染四空之所存者無幾，今遇佛字安得不斷。此那謨字正表界外見愛，所謂無明別惑。」
//   ——谱主径说「此那謨字」，是就本位之那謨立言，故通于本位诸组。
// 卷五〈八背捨觀〉譜曰：「那佛謨佛皆四果者，無漏定力但遇佛字必出生死。那謨以表法執，故為定性聲聞也。」
//   ——此语专释那佛、謨佛何以成「定性」声闻（法执未破故不迴心）；**不可推及三恶相**：
//   同段明写「謨謨鈍根那含者，思惑未盡，生四空天故」，可见謨謨在本位仍是思惑。故加 combos 限域。
export const POS_GLYPH = {
  鈍根阿那含: { glyph: { 那: '界外见惑', 謨: '界外爱惑' } },
  八背捨觀: { glyph: { 那: '法执', 謨: '法执' }, combos: ['那佛', '謨佛'] },
};

const EVIL = new Set(['那', '謨']);
/** 取某位某相中，某一轮字所表之义（已计入门位改判）。导出总表与话头共用同一取值口。 */
export function glyphMeaningOf(position, ch, combo) { return glyphOf(position, ch, combo); }
function glyphOf(position, ch, combo) {
  const ov = POS_GLYPH[position];
  if (ov && ov.glyph[ch] && (!ov.combos || ov.combos.includes(combo))) return ov.glyph[ch];
  return CANON_GLYPH[ch];
}

// 话头依卷首体例「X表Y」立文，以轮字自身称说（发起人定：保留「那那」这类说法，不改作「这一掷」）：
//   同字＝「『那那』二字俱表见烦恼」——「二字」是谱语（「儻不借用那謨二字表惡」「那謨二字既表見愛」）；
//   异字＝「『那』表见烦恼、『彌』表戒善」——与卷首「那表屬見煩惱」「彌表戒善」逐字同例。
//   轮字加「」者：那、陀等单字在白话中易与常用字相混，加引号方不误读。
//   内部只用「、」不用「，」：话头与判语以首个「，」或「。」为界，话头内出现「，」会切错。
export function canonLeadOf(position, combo) {
  const a = glyphOf(position, combo[0], combo);
  const b = glyphOf(position, combo[1], combo);
  return a === b
    ? `「${combo}」二字俱表${a}`
    : `「${combo[0]}」表${a}、「${combo[1]}」表${b}`;
}

