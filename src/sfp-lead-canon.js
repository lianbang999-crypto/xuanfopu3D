// 通例层（那阿等一惑一善六组）的旧句式：话头之后还有一截「一轮X、一轮Y之善，正好相抵。善压不住恶……」，
// 那一整截都要换，故单独认。
const STAY_OLD = /^[^，。]*，一轮[^，。]*、一轮[^，。]*之善，正好相抵。善压不住恶、恶也盖不过善，两边都使不上力，位次不动。$/;

// 2026-08-07 移植线上 V105（v409 通例层重写）后新增：
//   V105 把通例按位分作四式——①善惑对治 ②此位已伏住烦恼 ③已生净土永不退转 ④未掷到佛字。
//   后三式各有位别之据（忍位「不起惡故」／淨土疑城「永離退緣」／「唯得佛字方行」），本地无此分判，
//   一律不动，照 V105 上屏。**只有第①式**（467 格）仍走本地勘正：它释「相為對治」而未言「有漏」，
//   去之则谱主紧接的自破问答（「那佛謨佛亦可善惡相治，何以仍行？答：有漏惡劣……」）无从解释。
const STAY_V105_DUIZHI = /^一轮[^，。、]{1,8}[、，]一轮[^，。、]{1,10}，善与惑彼此对治，两边都发不出力，故这一掷不行。$/;

// 一惑一有漏善者，依卷一〈見取〉问答立说：善是有漏，故对治不成，二俱无力，所以不行。
// 「有漏」二字是这条通例的成立条件——去之则那佛、謨佛何以仍行便无从解释。
export function stayWhyCanon(position, combo) {
  const [a, b] = [combo[0], combo[1]];
  if (EVIL.has(a) === EVIL.has(b)) return '';        // 非一惑一善，不适用本通例
  const evilCh = EVIL.has(a) ? a : b;
  const goodCh = EVIL.has(a) ? b : a;
  if (goodCh === '佛') return '';                     // 佛是无漏善，谱主明言「不能障無漏善令總不行」
  const huo = glyphOf(position, evilCh, combo);
  const shan = CANON_GLYPH[goodCh];
  return `${canonLeadOf(position, combo)}。以有漏之${shan}对治${huo}，二俱无力`
    + `——善不足以断惑而升，惑也不足以致堕，所以不行。`;
}

/**
 * 把一格白话的话头换成卷首定诠之词；判语（首个「，」或「。」之后）一字不动。
 * 话头不在 KNOWN_LEADS 内者原样返回——宁可不改，不可误伤判语。
 */
export function applyCanonLead(text, position, combo) {
  if (!text || !combo || combo.length !== 2) return text;
  if (STAY_OLD.test(text) || STAY_V105_DUIZHI.test(text)) return stayWhyCanon(position, combo) || text;
  // 切分符须含「；」（2026-08-08 补）：上游有「爱烦恼夹一分布施；此处见惑不起现行……」一类，
  // 旧制只认逗号句号，话头遂被切成含分号后半段的一整句，永远落不进 KNOWN_LEADS，
  // 于是原样返回——「一分」这类不合卷首定诠的话头就这样漏了出去，而闸门只查已改写的格，查它不着。
  const at = text.search(/[，。；]/);
  if (at < 0) return KNOWN_LEADS.has(text) ? `${canonLeadOf(position, combo)}。` : text;
  const lead = text.slice(0, at);
  if (!KNOWN_LEADS.has(lead)) return text;
  return canonLeadOf(position, combo) + text.slice(at);
}
