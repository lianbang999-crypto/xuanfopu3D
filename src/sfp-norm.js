// 话头归一（v418）：game.ts 与 tools/audit-nocross.mjs 共用，避免两边漂移。
// 玩家只应读到自己这一掷：本组自称→「这一掷」；别组名字与枚举/索引片段→剔除；剥后补善恶配话头。
export const CROSS_ENUM = /[那謨阿彌陀佛]{2}\s*等\s*[一二三四五六七八九十]?/;
export function normLead(text, combo) {
  if (!text) return text;
  let s = text;
  s = s.replace(/「([那謨阿彌陀佛]{2})」/g, (m, g) => (g === combo ? '这一掷' : '\u0000' + g + '\u0000'));
  // 先处理「本组与别组并列」（「这一掷『謨佛』皆为…」「如这一掷至『佛佛』诸组」）：
  //   片段里既有本组自称又有别组名 → 只删别组名及其连接词，片段本身留给本组。
  s = s.replace(/(这一掷)\s*[、与和及至到]?\s*\u0000[那謨阿彌陀佛]{2}\u0000/g, '$1');
  s = s.replace(/\u0000[那謨阿彌陀佛]{2}\u0000\s*[、与和及至到]?\s*(这一掷)/g, '$1');
  // 含别组名的片段（到下一个分句为止）整段剔除
  s = s.replace(/[，,。；;：:]?\s*[^，。；：]*\u0000[那謨阿彌陀佛]{2}\u0000[^，。；：]*/g, '');
  s = s.replace(/\u0000/g, '');
  // 剥组名后可能留下断茬：「所以等三必堕」——把悬空的量词/助词一并清掉。
  // v431：「等」只在真悬空时清（句首/标点后 且 后接数词或组·诸组之类量词，且不是「等＋数＋实词」
  //   这种谱文表述）。句中的「等」属位名或谱文用字（等觉菩萨、六随顺平等善根回向、等三世佛、
  //   三等一切佛回向），一律保留——否则卡面吃字（实测「故入等觉菩萨」曾被吃成「故入觉菩萨」）。
  s = s.replace(/(^|[，,。；;：:、])\s*(?:所以|故|于是)?\s*等\s*(?:[一二三四五六七八九十]\s*(?:种)?(?:组合|诸组|组)?(?![^，。；：]*(?:世佛|一切佛|觉))|(?:种)?(?:组合|诸组|组))/g, '$1');

  // 枚举与索引语（「阿阿等六」「以下诸组」「其余诸组/行法」）
  s = s.replace(/[，,。；;：:]?\s*[^，。；：]*(?:其余诸组|其余行法|其余诸位|其他位中|以下诸组|以后诸组|中间诸组|以下诸位|下诸位|余组皆)[^，。；：]*/g, '');
  s = s.replace(new RegExp(`[，,。；;：:]?\\s*[^，。；：]*${CROSS_ENUM.source}[^，。；：]*`, 'g'), (m) => (m.includes('这一掷') ? m : ''));
  // 剥离后的语病收尾：「所以这一掷：」「如这一掷诸组」「故这一掷皆为」
  s = s.replace(/这一掷[：:]/g, '这一掷').replace(/这一掷\s*诸组/g, '这一掷')
       .replace(/这一掷\s*皆(?=[为成入生堕])/g, '这一掷').replace(/这一掷\s*等(?![一二三四五六七八九十])/g, '这一掷');
  s = s.replace(/^[，,。；;：:、]+/, '').replace(/[，,、；;]+$/, '').trim();
  s = s.replace(/[，,]{2,}/g, '，').replace(/。+/g, '。');
  if (s && !/[。！？]$/.test(s)) s += '。';
  return s;
}
// 归一后若只剩断语（甚至空），补上当下这一相的善恶配作话头（卷首〈輪相表法第一〉定诠）。
const GLYPH_W = { 那: '见烦恼', 謨: '爱烦恼', 阿: '布施', 彌: '持戒', 陀: '禅定', 佛: '智慧' };
export function comboLeadOf(c) {
  const a = c[0], b = c[1];
  const evil = (x) => x === '那' || x === '謨';
  if (a === b) return `两轮都是${GLYPH_W[a]}${evil(a) || a === '佛' ? '' : '之善'}`;
  if (evil(a) && evil(b)) return '见惑与爱惑并起';
  if (evil(a) !== evil(b)) { const e = evil(a) ? a : b, g = evil(a) ? b : a; return `${GLYPH_W[e]}夹一分${GLYPH_W[g]}`; }
  return `${GLYPH_W[a]}与${GLYPH_W[b]}之善`;
}
export function normWhy(text, combo) {
  const s = normLead(text, combo);
  if (!s || s === '。') return '';
  const lead = comboLeadOf(combo);
  // 已自带话头者不再叠加。「布施/持戒/禅定得智慧引导」也是卷首定诠的话头（X佛 三组），
  //   漏判会在卡面开头叠出两遍话头（「布施与智慧之善，布施得智慧引导。…」）。
  //   v433：四门义话头（生灭门/无生灭门/次第门/圆顿门的智慧）同为卷首第四重表法，一并认。
  // v437：四教门话头用词只取卷首〈輪相表法第一〉原词（见惑/思惑·施善/戒善/定善/善慧·
  //   无漏善慧·散善/定善），不再自造。白名单漏判会在卡面叠出两遍话头。
  const CANON_LEAD = /^(?:两轮都是(?:见烦恼|分别惑|见惑|见所断惑|爱烦恼|俱生惑|思惑|修所断惑|施善|戒善|定善|善慧|无漏善慧|有漏善|散善)|两轮同现(?:施善|戒善|定善|善慧|无漏善慧|散善)|(?:见|思)惑夹一分(?:施善|戒善|定善|散善|无漏善慧)|(?:施善|戒善|定善|散善)加(?:戒善|定善)|(?:施善|戒善|定善|散善|定善)引出(?:无漏善慧|妙慧)|见思二惑齐起|惑染二轮齐现|烦恼障二轮齐重|出观烦恼齐现|散善二轮齐现|定善二轮齐现|散善加定善|见惑未断而慧已生|思惑犹存而慧已发|见惑未断而无漏善慧已生|见断思存而无漏善慧已生|烦恼障重而慧已生|出观现起而慧已圆)/;
  // 本地补丁（2026-08-07 移植 V105 时实测）：v409/v416 新写的 STAY／GLYPH／MOVE 三库，
  //   主句一律改作「一轮X、一轮Y……」的自带话头式，而本白名单只认旧式（「两轮都是X」「见惑夹一分Y」），
  //   于是又补一个话头，屏上成了「见烦恼夹一分持戒，一轮见烦恼、一轮持戒之善，……」——同一句说两遍。
  //   线上 V105 现有 2545 格（STAY 995／GLYPH 866／MOVE 684）正是此状。本行即为此补。
  //   注：本文件原与线上逐字一致，此处是唯一的本地偏离，日后再复刻时须保留。
  if (s.startsWith('这一掷') || s.includes(lead)
      || /^一轮[^，。、]{1,8}[、，]一轮/.test(s)
      // 2026-08-08 补「兼一分」：善善相兼的二十三格（布施兼一分禅定／持戒兼一分禅定）
      //   本已是自带话头式，而此白名单只认「夹一分」，遂又补一个话头，屏上成了
      //   「「阿」表施善、「陀」表定善，布施兼一分禅定，微有定善……」——正是上文所记的同一句说两遍。
      || /^(?:两轮都是|见惑与爱惑并起|[^，。]{0,6}[夹兼]一分|(?:布施|持戒|禅定)得智慧引导|(?:生灭门|无生灭门|次第门|圆顿门)的智慧)/.test(s)
      || CANON_LEAD.test(s)) return s;
  return /^[不故此已]/.test(s) ? `${lead}；${s}` : `${lead}，${s}`;
}
