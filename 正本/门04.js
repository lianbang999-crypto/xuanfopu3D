//   夜摩天　上品十善兼**學坐禪**／不殺不盜不邪婬三戒／八戒十戒
//   兜率天　上品十善兼得**細住**／身三口四七支戒品／八戒十戒
//   化樂天　上品十善兼成**欲界中定**
//   他化天　上品十善兼成**未到地定**
//   ——定的一路：學坐禪→細住→欲界中定→未到地定；戒的一路：一戒→二戒→三戒→七支。
