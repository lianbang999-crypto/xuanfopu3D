// 【本门总关节】门首譜曰：「四洲四輪及與十仙皆人道攝。四王乃至他化名六欲天。
//   人天并前脩羅鬼畜皆有飲食男女睡眠三事。皆具色聲香味觸之五欲。故總名欲界也。
//   就四洲中若論福報則北洲最勝南洲最劣。若論見佛聞法則南洲最勝北洲最劣。
//   **今依見佛聞法以為次第。**十仙雖離人世不離人類。蒙光天子及內院總在兜率天中。
//   魔雖別有宮殿不出欲網還屬他化自在天攝。」
//   ★本门位次依「见佛闻法」而不依福报；第三门的两处位次疑点，仍应回到第三门原文核对，
//     不在本门门首另立解释。
