// 【本门总关节】门首譜曰：「**通前通後**。名為通教。直明因緣生法。**當體即空**。
//   利根之人。既見即空。**便見不空**。不空乃是中道實相。**則受別圓來接**。故名通後。
//   若鈍根人。但見於空。則觀慧雖巧。**終歸灰斷**。故名通前。又三乘之人。**同皆體色入空**。
//   故名通教。此教無別部帙。但諸大乘經中。有明三乘共得道者。即是同稟此教。**故有三乘共十地也**。」
//
//   门首这一段是全门的钥匙，四层意思：
//   ① **通前通後**——「通前」是钝根，但见于空而终归灰断，与藏教同一结局；
//      「通後」是利根，见空之后又见不空，被别教圆教接了去。全门的位次分岔就在这里。
//   ② **體色入空**——通教的观法是当体即空（体空观），与藏教析色明空（析法入空）正相对；
//      这是第十门与本门的分界，第十门门首「同修析觀」一句已先立。
//   ③ **三乘共十地**——本门十位是声闻、缘觉、菩萨三乘共走的十地，不是菩萨独有。
//      故第七已辦地下说「聲聞則從此止而不前」，第八辟支佛地下说「中乘根性。止此不前」。
//   ④ **則受別圓來接**——「被接」是本门独有的机制，含佛诸掷有六位全靠它，详见要害二。
//
