// 【要害五 · 两处「那那等三」反而行，各有其故】
//   作法懺→三品十惡：「**煩惱習強。悔已復犯。**」忏了又犯，反成十恶。
//   無生懺→聲聞心·辟支心：「**見思垢重。智慧狹劣。故雖觀無生。仍趣偏徑。**」
//   ——一处是犯而复犯则堕，一处是观而偏狭则小。
//
// 【要害六 · 無生懺本位仍属③层；「所观无生」另通乎四教】
//   因緣生滅。無實我法。故名無生（藏）／因緣即空。如幻如夢。故名無生（通）
//   因緣即假。虛妄有生。而中道之體雙非空有。故名無生（別）
//   因緣即中。深達罪相即是實相。不可思議。故名無生（圓）
//   ——本位不因此整体改判④层；阿阿、阿陀等格依谱文带出生灭门、次第门，字义仍按③层标注。
