//
// 【本门总关节】门首譜曰：「聽法。護法。請法。**令六道凡夫生出世善**。
//   作法取相無生三懺。**令三障重罪皆得滅除**。故為**入佛法之初門**。」
//   ——门名〈生善滅惡〉即此：前三位生善，后三位灭恶，合起来是入佛法的头一道门。
//
// 【六位的排法】
//   生善三位：聽法雜眾（听法）·護法八部（护法）·請法梵王（请法）
//   滅惡三位：作法懺（除小罪）·取相懺（灭重罪）·無生懺（塞其源）
//
// 【要害一 · 生善三位的烦恼掷不行，谱主逐位给了不同的理由】
//   聽法雜眾「**正聽法時。對治見思。令不現起。**」
//   護法八部「**既護正法。能伏見思現行。**」
//   請法梵王「**既已請轉法輪。即便能伏煩惱。**」
//   ——三位同是令见思、烦恼不起现行，但理由不同：听法是对治见思，护法是伏见思现行，
//     请法是请转法轮便能伏烦恼；凡本位不行格中含「那、謨」者，均应承接本位直接理由，
//     不再改套全谱末尾「惑善相为对治」的通例；三条本位理由也不可互换。
//
// 【要害二 · 聽法雜眾位把二十一相一刀切成两段】
//   「若生**世間有漏善根**。即感人天樂報。如阿阿至陀陀等。
//    若生**出世無漏善根**。即解三乘四教。如那佛至佛佛等。」
//   ——六纯善之掷是世间有漏善根，所感是人天乐报；带佛字六掷是出世无漏善根，
//     所解是三乘四教。全谱少见的整齐分判。
//
// 【要害三 · 三懺的分工，谱主定得极清楚】
//   作法懺：向清净师友发露悔除——「一往但能除滅小罪。**不能除滅根本重罪**也。」
//   取相懺：立坛结界、六时勤修五悔、哀求诸佛加被——「**能滅根本重罪。但未即滅七逆罪**耳。」
//   無生懺：观罪性空——「不論輕罪。重罪。十惡。七逆。先用作法取相而**導其流**。
//     隨即觀罪性空以**塞其源**。」
//   ★母本把这层递进也画出来了：作法懺位謨佛→取相懺、阿佛→無生懺，本位自己指向后二忏。
//   ★蕅益《占察善惡業報經行法》又明：「作法取相無生三種懺法。後後具於前前。前前亦通後後。
//     事理相扶。始終一致。」三懺虽有浅深分工，却彼此含摄，不是割裂的三法。（CBETA X74n1485_p0134a12）
//   ★《重治毗尼事義集要》明作法懺治轻罪须向清净比丘说罪、不敢覆藏；破法轮逆罪不可单作法懺，
//     须修無生懺，与本门轻重分判相合。（CBETA X40n0719_p0548a06）
//
// 【要害四 · 五清淨戒是一条阶梯，两懺所登不同】
