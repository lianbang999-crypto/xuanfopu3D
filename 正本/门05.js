// 【本门总关节】门首譜曰：「色界諸天。具有色受想行識五陰。無色界天。唯有受想行識四陰。
//   雖分二界八地……然同屬天趣。**同名定地**。故合為一門也。」
//   ——色界与无色界本是两界，所以能合为一门，只因同属天趣、同名「定地」。
//   世间禅天的升退多随定力与惑染而判；圣位、无想、无漏慧与净土等格，仍须各依本位判词。
//   门末归宗一句：「當知**有因即集諦。有果即苦諦**也。」——天再高仍是苦谛，不出轮回。
//
// 【二十三位的排法】色界十八天 ＋ 四空四天 ＋ 鈍根阿那含 ＝ 23
//   初禅三天（梵眾·梵輔·大梵）／二禅三天（少光·無量光·光音）／
//   三禅三天（少淨·無量淨·徧淨）／四禅三天（福生·福愛·廣果）／
//   無想天（外道所感，自为一有）／五不還天（無煩·無熱·善見·善現·色究竟，那含圣人寄居）／
//   四空天（空無邊·識無邊·無所有·非想非非想）／鈍根阿那含（寄四空处，无别处所）
//   ★谱主特别点出三处「自为一有」之故：大梵天**我慢最重**、無想天**唯外道所感**、
//     五不還天**唯那含聖人所寄居**。
